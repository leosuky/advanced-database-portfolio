#!/usr/bin/env python3
"""
Portfolio 2 benchmark runner.

1. Drops the Portfolio-2 indexes (so we measure the "before" state).
2. For every query in sql/01_queries.sql: saves EXPLAIN (ANALYZE, BUFFERS) and the median of RUNS timed executions.
3. Creates the indexes from sql/02_indexes.sql and repeats.
4. Writes results/plans_before/, results/plans_after/ and results/summary.md.

Usage:
    python run_benchmark.py --dsn "host=127.0.0.1 port=5433 dbname=dataxi user=postgres"
"""
import argparse
import os
import re
import statistics
import psycopg2

HERE = os.path.dirname(os.path.abspath(__file__))
RUNS = 15
INDEXES = ["idx_event_match", "idx_event_player_type", "idx_match_cs", "idx_match_home", "idx_match_away",
           "idx_player_match_team", "idx_player_match_player", "idx_shot_goals_late"]


def parse_queries(path):
    text = open(path).read()
    blocks = re.split(r"^-- name: ", text, flags=re.M)[1:]
    out = []
    for b in blocks:
        head, _, body = b.partition("\n")
        qid, _, title = head.partition("|")
        sql = "\n".join(l for l in body.splitlines() if not l.startswith("-- ====")).strip()
        out.append((qid.strip(), title.strip(), sql))
    return out


def run_phase(cur, queries, phase):
    d = os.path.join(HERE, "results", f"plans_{phase}")
    os.makedirs(d, exist_ok=True)
    res = {}
    for qid, title, sql in queries:
        times, plan_lines = [], None
        for i in range(RUNS):
            cur.execute("EXPLAIN (ANALYZE, BUFFERS, SETTINGS) " + sql.rstrip(";"))
            lines = [r[0] for r in cur.fetchall()]
            t = float(re.search(r"Execution Time: ([\d.]+) ms", "\n".join(lines)).group(1))
            if i > 0:                  # first run warms the cache; drop it
                times.append(t)
            plan_lines = lines
        with open(os.path.join(d, f"{qid}.txt"), "w") as f:
            f.write(f"-- {qid}: {title}\n-- phase: {phase}   median of {RUNS-1} warm runs: {statistics.median(times):.2f} ms\n\n")
            f.write(sql + "\n\n")
            f.write("\n".join(plan_lines) + "\n")
        main_node = next((l.strip() for l in plan_lines if "->" in l or "Scan" in l or "Aggregate" in l), plan_lines[0])
        scans = sorted(set(re.findall(r"(Seq Scan|Index Only Scan|Index Scan|Bitmap Heap Scan|Parallel Seq Scan)", "\n".join(plan_lines))))
        res[qid] = (title, statistics.median(times), scans)
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dsn", default="host=127.0.0.1 port=5433 dbname=dataxi user=postgres")
    a = ap.parse_args()
    conn = psycopg2.connect(a.dsn)
    conn.autocommit = True
    cur = conn.cursor()
    cur.execute("SET search_path = dataxi, public")
    cur.execute("SET max_parallel_workers_per_gather = 0")   # single worker: keeps before/after comparable
    queries = parse_queries(os.path.join(HERE, "sql", "01_queries.sql"))

    for ix in INDEXES:
        cur.execute(f"DROP INDEX IF EXISTS dataxi.{ix}")
    cur.execute("ANALYZE")
    before = run_phase(cur, queries, "before")

    cur.execute(open(os.path.join(HERE, "sql", "02_indexes.sql")).read())
    after = run_phase(cur, queries, "after")

    cur.execute("SELECT indexrelname, pg_size_pretty(pg_relation_size(indexrelid)) FROM pg_stat_user_indexes "
                "WHERE schemaname='dataxi' AND indexrelname = ANY(%s) ORDER BY 1", (INDEXES,))
    sizes = cur.fetchall()

    with open(os.path.join(HERE, "results", "summary.md"), "w") as f:
        f.write("# Benchmark summary (generated by run_benchmark.py)\n\n")
        f.write(f"Median of {RUNS-1} warm runs, `EXPLAIN (ANALYZE)` execution time, parallel workers off.\n\n")
        f.write("| Query | What it does | Before (ms) | After (ms) | Speed-up | Scans before -> after |\n|---|---|---:|---:|---:|---|\n")
        for qid, (title, tb, sb) in before.items():
            _, ta, sa = after[qid]
            f.write(f"| {qid} | {title} | {tb:.1f} | {ta:.1f} | {tb/ta:.1f}x | {', '.join(sb)} -> {', '.join(sa)} |\n")
        f.write("\n## Index sizes\n\n| Index | Size |\n|---|---|\n")
        for n, s in sizes:
            f.write(f"| {n} | {s} |\n")
    print(open(os.path.join(HERE, "results", "summary.md")).read())


if __name__ == "__main__":
    main()
